import React from "react";

// عرض موحّد لأي قيمة رقمية مفردة (سعرات/وزن/نسبة/تاريخ/وقت...) داخل نص أو
// بطاقة عربية - يضمن دائماً أمرين (راجع تقرير فحص RTL/الأرقام):
// (1) أرقام إنجليزية فقط، بلا أي احتمال تحوّل لأرقام هندية عربية (بعض
//     استدعاءات toLocaleString بلغة عربية تفعل هذا تلقائياً لو استُخدمت
//     هنا - لذا هذا المكوّن يعرض القيمة كنص مباشر (String) دون أي تنسيق
//     محلي (locale-aware)، وهذا يكفي وحده لضمان أرقام لاتينية دائماً لأن
//     تحويل الأرقام لأرقام هندية لا يحدث إلا عبر Intl/toLocaleString بلغة
//     عربية تحديداً - String()/toString() في جافاسكربت لاتيني دائماً بلا
//     استثناء بغضّ النظر عن أي إعداد لغة).
// (2) عزل اتجاهي (bidi isolate) حول الرقم والوحدة معاً كوحدة واحدة، عبر
//     عنصر <bdi> (Bidirectional Isolate - عنصر HTML قياسي مصمَّم لضبط هذا
//     بالضبط) مع dir="ltr" صريح، حتى لا ينكسر ترتيب أي نص عربي محيط بها
//     مهما كان موضعها في الجملة.
//
// value: رقم، أو نص جاهز (نطاق مثل "25-30"، أو نص وقت/تاريخ مُنسَّق مسبقاً)
//   - يُعرَض كما هو دون أي تقريب أو تنسيق إضافي من هذا المكوّن (المستدعي
//   مسؤول عن التقريب/التنسيق قبل التمرير، كما كان يفعل دائماً في كل مكان).
// unit: وحدة قصيرة اختيارية (سعرة, غ, %, كغ...) تُعرض بعد الرقم مباشرة
//   بمسافة رفيعة - جزء من نفس كتلة العزل (لا تنفصل بصرياً عن رقمها أبداً).
// signed: يضيف علامة "+" صراحة أمام أي قيمة رقمية موجبة (لعرض فروقات مثل
//   "+2.5 كغ عن آخر مرة") - القيم السالبة تحمل "-" تلقائياً من جافاسكربت
//   نفسه فلا حاجة لأي معالجة إضافية لها.
// style: تنسيق إضافي اختياري يُدمَج فوق التنسيق الافتراضي (fontVariantNumeric
//   tabular-nums، بنفس نمط hStat الموجود أصلاً في styles.js).
export default function NumericValue({ value, unit, signed = false, style }) {
  const isNum = typeof value === "number" && Number.isFinite(value);
  const display = isNum && signed && value > 0 ? `+${value}` : String(value);
  return (
    <bdi dir="ltr" style={{ unicodeBidi: "isolate", fontVariantNumeric: "tabular-nums", ...style }}>
      {display}
      {unit ? ` ${unit}` : ""}
    </bdi>
  );
}
