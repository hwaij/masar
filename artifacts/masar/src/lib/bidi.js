// أدوات عزل اتجاهي (Unicode Bidi) للأرقام الإنجليزية داخل نص عربي (RTL) -
// نفس المبدأ العلمي المستخدم أصلاً في achievementShare.js (بطاقة الإنجاز
// المُصدَّرة كـCanvas، حيث ctx.fillText لا يطبّق خوارزمية Unicode Bidi
// إطلاقاً فتحتاج عزلاً يدوياً كاملاً) لكن هنا للنصوص الحقيقية في الصفحة
// (DOM حقيقي)، حيث متصفح المستخدم يطبّق خوارزمية Unicode Bidi تلقائياً على
// كل نص - لكنها غير كافية وحدها مع فقرات حرة (ردود ذكاء اصطناعي، توصيات
// تقارير) تحتوي عدة أرقام/فروقات موقَّعة (+/-)/نطاقات (5-10) متناثرة داخل
// جملة عربية طويلة (راجع تقرير الفحص: هذه أنماط فشل فعلية موجودة، لا
// افتراضية).
//
// RLI/PDI (Right-to-Left Isolate / Pop Directional Isolate، معيار Unicode
// Bidi رسمي، Unicode 6.3+) يخبران المتصفح: "هذا المقطع بينهما اتجاهه
// الداخلي مستقل تماماً عن محيطه - اعرضه بمنطقه الخاص ثم عد فوراً لاتجاه
// النص المحيط تماماً كما كان" - هذا بالضبط ما يحتاجه أي رقم لاتيني (أو
// نطاق/إشارة) داخل جملة عربية، بلا أي تأثير مرئي (لا مسافة، لا لون، لا
// تغيير للنص نفسه - علامتان غير مرئيتين فقط).
const RLI = "⁧";
const PDI = "⁩";

// يعزل أي "تشغيلة أرقام" داخل نص حر: رقم صحيح أو عشري، إشارة +/- أمامية
// (فرق موقَّع مثل "+2.5")، أو نطاق أرقام متصل بشرطة ("25-30" أو "25 - 30")،
// مع علامة % لاحقة اختيارية. لا يُغيّر الرقم نفسه إطلاقاً (يبقى إنجليزياً
// تماماً كما ورد من المصدر) - فقط يضيف علامتي عزل غير مرئيتين حوله.
//
// آمنة للاستدعاء على أي نص بلا فحص لغة مسبق (بما في ذلك نص إنجليزي بالكامل
// أو بلا أي أرقام) - RLI/PDI حول رقم داخل جملة LTR بالفعل لا أثر مرئي أو
// وظيفي له، فيمكن تطبيقها دائماً كخطوة أخيرة قبل العرض دون أي شرط.
const NUMBER_RUN_RE = /[+-]?\d+(?:[.,]\d+)?(?:\s*-\s*\d+(?:[.,]\d+)?)?%?/g;

export function isolateNumbers(text) {
  if (!text) return text;
  return String(text).replace(NUMBER_RUN_RE, (m) => `${RLI}${m}${PDI}`);
}
